#!/usr/bin/env python3
"""Generate docs/SUMMARY.md (the mdBook table of contents) from the doc map.

r5 F5-10: SUMMARY.md is generated from the Project Overview's document map
(§8 "Where everything lives"), so the map stays the one source of truth for
what the book contains. Python 3.12, stdlib only (AGENTS.md §10).

Rules, in full:

1. Read the first Markdown table under the "(document map)" heading of the
   Overview. Each row's first cell names documents in `backticks`;
   "**This file**" names the Overview itself.
2. A backticked name that exists under docs/ is used as-is. Shorthand
   continues the previous name: `-r2.md` appends to its stem
   (`ADR-001-adversarial-review.md` -> `ADR-001-adversarial-review-r2.md`);
   `r4.md` replaces its last word (`... Review r3.md` -> `... Review r4.md`).
   A name that still does not resolve is an error.
3. A mapped `<dir>/README.md` pulls in every other `.md` file in that
   directory as sorted sub-chapters (runbook entries, protocol chapters),
   so per-gate files never need a map row.
4. Every `.md` file under docs/ must end up in the book: an unmapped
   document is an error, so the map cannot silently fall behind the corpus.
5. Chapter titles are file stems; links encode spaces as %20 (the only
   escape mdBook 0.4 decodes in SUMMARY.md).

Usage:
    python3 ops/docs-summary.py           # rewrite docs/SUMMARY.md
    python3 ops/docs-summary.py --check   # exit 1 if the committed file differs
"""

from __future__ import annotations

import difflib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
OVERVIEW = "mini-headend Project Overview — Faithful Lab Reproduction.md"
SUMMARY = DOCS / "SUMMARY.md"
# Files that are book plumbing, not chapters.
NOT_CHAPTERS = {"SUMMARY.md"}

HEADER = """\
# Summary

<!-- GENERATED by ops/docs-summary.py from the document map in
     "{overview}" §8. Do not edit by hand:
     change the map, then run `python3 ops/docs-summary.py`.
     CI (`mdbook (link check)`) fails when this file is stale. -->

"""


class MapError(Exception):
    pass


def map_rows(overview_text: str) -> list[str]:
    """Return the first cell of every body row of the document-map table."""
    lines = overview_text.splitlines()
    try:
        start = next(
            i for i, l in enumerate(lines)
            if l.startswith("#") and "(document map)" in l
        )
    except StopIteration:
        raise MapError(f"no '(document map)' heading in {OVERVIEW}") from None
    cells: list[str] = []
    in_table = False
    for line in lines[start + 1:]:
        if line.startswith("|"):
            in_table = True
            cells.append(line.split("|")[1].strip())
        elif in_table or line.startswith("#"):
            break
    if len(cells) < 3:
        raise MapError("document-map table not found or empty")
    return cells[2:]  # drop header row and the --- separator row


def resolve(token: str, prev: str | None) -> str:
    """Resolve one backticked map name to a docs/-relative path."""
    if (DOCS / token).is_file():
        return token
    if prev is not None:
        stem = prev[: -len(".md")]
        if token.startswith("-"):
            candidate = stem + token
        else:
            candidate = stem.rsplit(" ", 1)[0] + " " + token
        if (DOCS / candidate).is_file():
            return candidate
    raise MapError(f"document map names `{token}`, which is not a file under docs/")


def mapped_documents(overview_text: str) -> list[str]:
    docs: list[str] = []
    for cell in map_rows(overview_text):
        if cell.replace("*", "").strip().lower() == "this file":
            docs.append(OVERVIEW)
            continue
        prev = None
        for token in re.findall(r"`([^`]+)`", cell):
            if not token.endswith(".md"):
                continue
            prev = resolve(token, prev)
            docs.append(prev)
    seen: set[str] = set()
    ordered = []
    for d in docs:
        if d in seen:
            raise MapError(f"document map lists `{d}` twice")
        seen.add(d)
        ordered.append(d)
    return ordered


def link(rel: str) -> str:
    # mdBook 0.4 resolves SUMMARY links by decoding only %20 (it does not
    # percent-decode UTF-8 sequences), so encode exactly the spaces and
    # keep em-dashes, '&', ',' and balanced '()' literal.
    return rel.replace(" ", "%20")


def title(rel: str) -> str:
    p = Path(rel)
    if p.name == "README.md":
        return p.parent.name.capitalize() if str(p.parent) != "." else "README"
    return p.stem


def render() -> str:
    overview_text = (DOCS / OVERVIEW).read_text(encoding="utf-8")
    entries = mapped_documents(overview_text)
    out = [HEADER.format(overview=OVERVIEW)]
    included: set[str] = set()
    for rel in entries:
        out.append(f"- [{title(rel)}]({link(rel)})\n")
        included.add(rel)
        p = Path(rel)
        if p.name == "README.md" and str(p.parent) != ".":
            children = sorted(
                c.relative_to(DOCS).as_posix()
                for c in (DOCS / p.parent).glob("*.md")
                if c.name != "README.md"
            )
            for child in children:
                out.append(f"  - [{title(child)}]({link(child)})\n")
                included.add(child)
    corpus = {
        p.relative_to(DOCS).as_posix()
        for p in DOCS.rglob("*.md")
        if p.name not in NOT_CHAPTERS
    }
    missing = sorted(corpus - included)
    if missing:
        raise MapError(
            "documents not reachable from the document map (add a row to "
            f"{OVERVIEW} §8, or put them under a mapped <dir>/README.md): "
            + ", ".join(missing)
        )
    return "".join(out)


def main(argv: list[str]) -> int:
    check = "--check" in argv[1:]
    try:
        text = render()
    except MapError as e:
        print(f"docs-summary: {e}", file=sys.stderr)
        return 1
    if check:
        current = SUMMARY.read_text(encoding="utf-8") if SUMMARY.exists() else ""
        if current != text:
            sys.stderr.writelines(
                difflib.unified_diff(
                    current.splitlines(True), text.splitlines(True),
                    "docs/SUMMARY.md (committed)", "docs/SUMMARY.md (generated)",
                )
            )
            print(
                "docs-summary: docs/SUMMARY.md is stale; run "
                "`python3 ops/docs-summary.py` and commit the result",
                file=sys.stderr,
            )
            return 1
        print("docs-summary: docs/SUMMARY.md matches the document map")
        return 0
    SUMMARY.write_text(text, encoding="utf-8")
    print(f"docs-summary: wrote {SUMMARY.relative_to(ROOT)} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
